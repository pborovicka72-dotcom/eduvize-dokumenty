import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const source=html.match(/async function renderPdfSheets\([\s\S]*?\n\}(?=\nfunction updatePageButtons)/)[0];
const requested=[],grid={style:{setProperty(){}},clientWidth:500,clientHeight:400,children:[],replaceChildren(){this.children=[]},append(n){this.children.push(n)}};
const pdf={numPages:5,async getPage(n){requested.push(n);return {getViewport:({scale})=>({width:100*scale,height:200*scale}),render:()=>({promise:Promise.resolve()})}}};
let enlarged;
const context={directDocument:true,pdfPage:0,pdfColumns:3,pdfTotal:5,pdfZoomed:false,pdfRenderId:1,Math,enlargePdfPage:n=>enlarged=n,showPdfOverview(){},node:()=>({style:{},classList:{toggle(){}},dataset:{},setAttribute(){},getContext(){return {}}})};
vm.runInNewContext(source,context);
await context.renderPdfSheets(pdf,grid,1);
assert.deepEqual(requested,[1,2,3]);assert.equal(grid.children.length,3);assert.ok(grid.children[0].height<=376);
grid.children[1].onclick();assert.equal(enlarged,1);
context.pdfPage=3;await context.renderPdfSheets(pdf,grid,1);assert.equal(grid.children.length,2);
context.pdfPage=4;context.pdfColumns=1;context.pdfZoomed=true;await context.renderPdfSheets(pdf,grid,1);assert.equal(grid.children.length,1);
await context.renderPdfSheets(pdf,grid,0);assert.equal(grid.children.length,1);
assert.ok(html.includes('Načítám dokument…'));
assert.ok(html.includes('html.document-output #heading{display:none}'));
console.log('PDF overview renders up to three pages, supports enlarging and protects current render.');
