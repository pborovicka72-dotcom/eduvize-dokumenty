def png():
    def chunk(t,b):return struct.pack('!I',len(b))+t+b+struct.pack('!I',zlib.crc32(t+b)&0xffffffff)
    width,height=800,450;rows=b''.join(b'\x00'+bytes((30,95,130))*width for _ in range(height))
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!IIBBBBB',width,height,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(rows))+chunk(b'IEND',b'')
def pdf():
    contents=[b'BT /F1 24 Tf 60 700 Td (TEST DOCUMENT PAGE 1) Tj ET',b'BT /F1 24 Tf 60 700 Td (TEST DOCUMENT PAGE 2) Tj ET']
    objects=[b'<< /Type /Catalog /Pages 2 0 R >>',b'<< /Type /Pages /Count 2 /Kids [3 0 R 4 0 R] >>',b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 7 0 R >> >> /Contents 5 0 R >>',b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 7 0 R >> >> /Contents 6 0 R >>']
    objects += [b'<< /Length '+str(len(c)).encode()+b' >>\nstream\n'+c+b'\nendstream' for c in contents]
    objects += [b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>']
    out=bytearray(b'%PDF-1.4\n');offsets=[0]
    for i,obj in enumerate(objects,1):offsets.append(len(out));out.extend(str(i).encode()+b' 0 obj\n'+obj+b'\nendobj\n')
    start=len(out);out.extend(b'xref\n0 8\n0000000000 65535 f \n')
    for offset in offsets[1:]:out.extend(f'{offset:010d} 00000 n \n'.encode())
    out.extend(b'trailer\n<< /Size 8 /Root 1 0 R >>\nstartxref\n'+str(start).encode()+b'\n%%EOF\n')
    return bytes(out)
